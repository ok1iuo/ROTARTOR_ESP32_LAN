# Pre-build script: generates include/fw_version.h with FW_VERSION taken from git.
# On a tagged commit the version is the tag (e.g. "0.0.1"); between tags git describe
# appends the commit count and hash (e.g. "0.0.1-3-g1a2b3c4"); "-dirty" marks local changes.
import os
import subprocess

Import("env")

project_dir = env.subst("$PROJECT_DIR")

try:
    version = subprocess.check_output(
        ["git", "describe", "--tags", "--always", "--dirty"],
        cwd=project_dir, stderr=subprocess.DEVNULL).decode().strip()
except Exception:
    version = "unknown"

header_path = os.path.join(project_dir, "include", "fw_version.h")
content = ("// Generated by scripts/version.py - do not edit, do not commit\n"
           "#pragma once\n"
           "#define FW_VERSION \"%s\"\n" % version)

old_content = None
if os.path.exists(header_path):
    with open(header_path) as f:
        old_content = f.read()
if content != old_content:
    with open(header_path, "w") as f:
        f.write(content)

print("Firmware version: " + version)
